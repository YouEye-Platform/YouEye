export const serverNames = Object.values(nameRegistry).flat();
export const pick = <T>(items: readonly T[], random: () => number) =>
  items[Math.min(items.length - 1, Math.floor(random() * items.length))];
export function randomName(current = "", random = Math.random) {
  return pick(
    serverNames.filter((name) => name !== current),
    random,
  );
}
