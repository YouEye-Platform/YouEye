export function iconPalette([
  ,
  ink,
  background,
  pale,
]: string[]): Partial<Icon> {
  const darker =
    "#" +
    [1, 3, 5]
      .map((at) =>
        Math.round(parseInt(ink.slice(at, at + 2), 16) * 0.6)
          .toString(16)
          .padStart(2, "0"),
      )
      .join("");
  return {
    background,
    backgroundDark: ink,
    accent: pale,
    accentDark: darker,
    foreground: ink,
    foregroundDark: pale,
    match: false,
  };
}
