test('restore applies encrypted core and app volume maps before completion', () => {
  const full = read('src/lib/backup/full-restore.ts');
  const app = read('src/lib/backup/app-restore.ts');
  const postgres = read('src/lib/backup/postgres.ts');
  const spine = read('src/lib/spine/client.ts');
  assert.match(spine, /Promise<\{ staging_dir: string; message: string \}>/);
  assert.doesNotMatch(`${full}\n${app}`, /restoreArchive[\s\S]{0,300}\.status/);
  assert.match(full, /applyBackupVolumes\(coreStagingDir\)/);
  assert.match(full, /throw new Error\(`No core backup found/);
  assert.match(full, /RESTORE_CONTAINER_START_ATTEMPTS = 5/);
  assert.match(full, /for \(const container of quiesced\)/);
  assert.match(full, /runningContainers\(\[container\]\)[\s\S]{0,40}\.includes\(container\)/);
  assert.doesNotMatch(full, /Promise\.allSettled\(quiesced/);
  assert.match(app, /applyBackupVolumes\(stagingDir\)/);
  assert.match(full, /unexpected database dump/);
  assert.match(full, /isPlatformDatabase\(dbName\)/);
  assert.match(full, /replacePlatformDatabase/);
  assert.match(app, /replacePlatformAppDatabase/);
  assert.match(postgres, /replacePlatformAppDatabase[\s\S]*await applyPostgresDump\(\{[\s\S]*database,[\s\S]*user,[\s\S]*dump: options\.dump/);
  assert.match(app, /restoreOwnPostgresDatabase/);
  assert.match(app, /validateOwnPostgresStorageContract/);
  assert.match(app, /Restored the encrypted database dump/);
  assert.match(app, /containerName !== container/);
  assert.match(postgres, /DROP DATABASE IF EXISTS \$\{databaseIdentifier\}/);
  assert.match(app, /postInstallOwnDatabaseRestore/);
  assert.match(app, /waitForOperation\(response\.operation, 60\)/);
  assert.match(app, /startContainerAfterRestore/);
  assert.match(app, /if \(existsSync\(ownDumpPath\)\)/);
  assert.match(app, /Shared databases and volumes were restored before install/);
  assert.doesNotMatch(app, /Promise\.allSettled\(stoppedContainers/);
  assert.match(postgres, /DROP DATABASE IF EXISTS/);
  assert.match(postgres, /CREATE DATABASE/);
  assert.doesNotMatch(`${full}\n${app}`, /execShell|base64.*psql|-U postgres/);
  assert.doesNotMatch(full, /youeye-authentik|restart-authentik/);
  assert.match(app, /invalid own-database restore metadata/);
});
